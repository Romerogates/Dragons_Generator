const KEYWORD_FILES: readonly { key: string; file: string }[] = PAINTED_ICON_GROUPS.flatMap(
  ([keys, file]) => keys.map((key) => ({ key, file })),
).sort((a, b) => b.key.length - a.key.length || a.key.localeCompare(b.key));

export function isPaintedAssetPath(icon: string): boolean {
  return icon.startsWith('/assets/');
}

/** Portraits `ui-*` uniques, pour le sélecteur d’avatar. */
export function uniqueUiPortraitIcons(): readonly { icon: string; file: string }[] {
  const seen = new Set<string>();
  const out: { icon: string; file: string }[] = [];
  for (const [icon, file] of Object.entries(EXACT)) {
    if (!file.includes('/ui-')) continue;
    if (seen.has(file)) continue;
    seen.add(file);
    out.push({ icon, file });
  }
  return out;
}

/** Portrait peint pour un id Iconify ou un chemin déjà `/assets/…`. */
export function resolvePaintedIcon(icon: string | null | undefined): string {
  const raw = (icon ?? '').trim();
  if (!raw) return A('adv-backpack.png');
  if (raw.startsWith('/assets/')) return raw;
  const mapped = EXACT[raw];
  if (mapped) return mapped;
  if (!raw.startsWith('fluent-emoji:')) return raw;
  const id = raw.slice('fluent-emoji:'.length);
  for (const { key, file } of KEYWORD_FILES) {
    if (iconIdHasKeyword(id, key)) return file;
  }
  return A('ui-sparkles.png');
}

function iconIdHasKeyword(id: string, key: string): boolean {
  if (id === key) return true;
  return id.startsWith(`${key}-`) || id.endsWith(`-${key}`) || id.includes(`-${key}-`);
}
